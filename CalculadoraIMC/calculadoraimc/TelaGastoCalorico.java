    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        String textoAltura = txtAltura.getText().trim();
        String textoPeso = txtPeso.getText().trim();
        String textoIdade = txtIdade.getText().trim();

        if(textoPeso.isEmpty() || textoAltura.isEmpty() || textoIdade.isEmpty()){
            JOptionPane.showMessageDialog(this, "Prencha os campos");
            return;
        }
        double calBasal = 0;
        double calTotal = 0;
        try{

            String alturaLimpa = textoAltura.replace(",", "").replace(".", "");
            double altura = Double.parseDouble(alturaLimpa);

            if(altura <= 0 || altura > 250){
                JOptionPane.showMessageDialog(this, "Altura Inválido informe uma Altura entre 0 e 250 cm");
                return;
            }

            double peso = Double.parseDouble(textoPeso.replace(",","."));

            if(peso <= 0 || peso > 300){

                JOptionPane.showMessageDialog(this, "Peso Inválido informe um peso entre 0 e 300 kg");
                return;

            }

            String idadeLimpa = textoIdade.replace(",", "").replace(".", "");
            double idade = Double.parseDouble(idadeLimpa);

            if (idade < 0 || idade > 120){

                JOptionPane.showMessageDialog(this, "Idade Inválida informe uma idade entre 0 e 120 anos");
                return;
            }

            if (jrHomem.isSelected()){
                calBasal = 66 + (13.8 * peso) + (5 * altura)- (6.8 * idade);
            }

            else if(jrMulher.isSelected()){
                calBasal = 655 + (9.6 * peso) + (1.9 * altura)- (4.7 * idade);
            }

            else {

                JOptionPane.showMessageDialog(this, "Selecione o sexo (Homem ou Mulher)");
                return;
            }

            lblValorGastoCal.setText(String.format("%.2f",calBasal));

          int nivelEscolhido = cmbNivelAtiv.getSelectedIndex(); 
          
           if (nivelEscolhido == 0) {
           calTotal = calBasal * 1.2;
                   
            }else if( nivelEscolhido == 1){
            calTotal = calBasal * 1.375;
                    
            }else if (nivelEscolhido == 2){
            calTotal = calBasal * 1.55;
           
            }else if (nivelEscolhido == 3){
            calTotal = calBasal * 1.725;
                    
            }else if (nivelEscolhido == 4){
            calTotal = calBasal * 1.9;
            
            }else{
            JOptionPane.showMessageDialog(this, "Selecione um nivel de Atividade");
            return;
            }
                    
                    
            lblValorGastoTot.setText(String.format("%.2f",calTotal));

        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Informe apenas numeros validos");
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnCalcularActionPerformed

