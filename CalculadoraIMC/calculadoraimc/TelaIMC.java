    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
String textoAltura = txtAltura.getText();
String textoPeso = txtPeso.getText();

    if(textoPeso.isEmpty() || textoAltura.isEmpty()){
    JOptionPane.showMessageDialog(this, "Prencha os campos");   
    return;
}
try{
    
    double altura = Double.parseDouble(textoAltura.replace(",","."));
    
    if(altura <= 0 || altura > 2.50){
       JOptionPane.showMessageDialog(this, "Informe uma Altura entre 0 e 2.50 m");
       return;
    }
    
    double peso = Double.parseDouble(textoPeso.replace(",","."));
    
    
if(peso <= 0 || peso > 300){
       JOptionPane.showMessageDialog(this, "Informe um peso entre 0 e 300 kg");
       return;
}
    
    double imc = peso / (altura * altura);

    lblValorResultado.setText(String.format("%.2f",imc));
    
        if(imc < 18.5){
        lblValorInterpretacao.setText("Magreza");
        
        } else if (imc < 25) {
            lblValorInterpretacao.setText("Normal");

        } else if (imc < 30) {
            lblValorInterpretacao.setText("Sobrepeso");

        } else if (imc < 40) {
            lblValorInterpretacao.setText("Obesidade");

        } else {
            lblValorInterpretacao.setText("Obesidade grave");
        }

    
}catch(NumberFormatException e){
    JOptionPane.showMessageDialog(this, "Informe apenas numeros validos");
}


// 


    }//GEN-LAST:event_btnCalcularActionPerformed

