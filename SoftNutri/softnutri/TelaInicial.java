    private void btnExcluirConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirConsultaActionPerformed
int linhaSelecionada = tblConsultas.getSelectedRow();

if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecione uma consulta para excluir."
    );
    return;
}

int resposta = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Deseja realmente excluir esta consulta?",
        "Confirmar exclusão",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (resposta == javax.swing.JOptionPane.YES_OPTION) {
    Dados.consulta.remove(linhaSelecionada);
    atualizarTabela();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Consulta excluída com sucesso."
    );
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnExcluirConsultaActionPerformed

    private void btnFinalizarConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarConsultaActionPerformed
int linhaSelecionada = tblConsultas.getSelectedRow();

if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Selecione uma consulta para finalizar."
    );
    return;
}

Consulta consultaSelecionada = Dados.consulta.get(linhaSelecionada);

TelaDetalhesConsulta tela = new TelaDetalhesConsulta();
tela.setConsulta(consultaSelecionada);
tela.setTelaInicial(this);
tela.setVisible(true);   

// TODO add your handling code here:
    }//GEN-LAST:event_btnFinalizarConsultaActionPerformed

