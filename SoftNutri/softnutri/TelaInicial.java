public void atualizarTabela() {

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblConsultas.getModel();

    modelo.setRowCount(0);

    for (Consulta consulta : Dados.consulta) {

       modelo.addRow(new Object[]{
    consulta.getNome(),
    consulta.getCpf(),
    consulta.getTelefone(),
    consulta.getData_consulta(),
    consulta.getJa_paciente() ? "Sim" : "Não",
    consulta.getJa_realizado() ? "Sim" : "Não"
});
    }
}
