    public void setConsulta(Consulta consulta) {
        this.consulta = consulta;
        chckConsultaRealizada.setSelected(consulta.getJa_realizado());
        
        
    if (consulta.getJa_realizado()) {
        chckConsultaRealizada.setEnabled(false);
        txtObservacao.setText(consulta.getObservacoes());
        btnFinalizar.setVisible(false);
    } else {
        chckConsultaRealizada.setSelected(false);
        chckConsultaRealizada.setEnabled(true);
        txtObservacao.setText("");
        btnFinalizar.setVisible(true);
    }
        
        
    }
