    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed

        String observacoes = txtObservacao.getText().trim();

if (observacoes.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Informe a receita e/ou observações antes de finalizar."
    );
    return;
}

try {
    if (consulta == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Nenhuma consulta foi selecionada."
        );
        return;
    }

    consulta.setObservacoes(observacoes);
    consulta.setJa_realizado(true);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Consulta finalizada com sucesso!"
    );
telaInicial.atualizarTabela();
    this.dispose();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Erro ao finalizar a consulta."
    );
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnFinalizarActionPerformed

